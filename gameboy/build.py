#!/usr/bin/env python3
"""Build the Game Boy module and put it into a firmware image.

  build.py [--date 2026-10-27] [--name "Game Boy"] [--stock firmware/HIFIYF18.IMG]

The module replaces one stock game (Tank Battle in v1.7.8) and the games
stored right after it. It plays the Game Boy ROMs (*.GB) in the root of the
player's storage, chosen from a list and read in pages on demand.

Every firmware address comes from the table in fw/ whose sha256 matches the
stock image. For a firmware version without a table, tools/findaddrs.py
writes a first draft; this script refuses a table that is not marked
"verified" unless --allow-unverified is given.
Output: build/gb/<same file name as the stock image>
"""
import argparse, glob, hashlib, json, os, shutil, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "build", "gb")
sys.path.insert(0, os.path.join(ROOT, "tools"))
from toolchain import tool
CODE_ROOM = 0x4a3c        # RAM kept for code above the games' load address; cache pool B starts after it


def load_table(stock, allow_unverified):
    sha = hashlib.sha256(stock).hexdigest()
    for path in sorted(glob.glob(os.path.join(ROOT, "fw", "*.json"))):
        t = json.load(open(path))
        if t.get("sha256") == sha:
            break
    else:
        sys.exit("no address table in fw/ for this firmware (sha256 %s).\n"
                 "Make a draft with:  python tools/findaddrs.py IMAGE -o fw/NAME.json\n"
                 "then check it and test in the harness before flashing." % sha)
    if t.get("missing"):
        sys.exit("%s: still missing %s" % (os.path.relpath(path, ROOT), ", ".join(t["missing"])))
    if not t.get("verified") and not allow_unverified:
        sys.exit("%s is a draft that nobody has verified. Flashing a build made from wrong addresses can "
                 "brick the player. Use --allow-unverified to build anyway." % os.path.relpath(path, ROOT))
    if not t["game"].get("menu_name"):
        sys.exit("%s: game.menu_name (the menu entry of module %s) is not filled in" % (os.path.relpath(path, ROOT), t["game"].get("slot")))
    return t, os.path.relpath(path, ROOT)


def run(*cmd):
    subprocess.run(cmd, check=True)


def syms(elf):
    out = subprocess.run([tool("llvm-nm"), elf], check=True, capture_output=True, text=True).stdout
    return {p[-1]: int(p[0], 16) for p in (l.split() for l in out.splitlines()) if len(p) == 3}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--date", default="2026-10-27")
    ap.add_argument("--name", default="Game Boy", help="menu name that replaces Tank Battle")
    ap.add_argument("--opt", default="-O2")
    ap.add_argument("--allow-unverified", action="store_true", help="build from an address table nobody has checked")
    ap.add_argument("--stock", default=os.path.join(ROOT, "firmware", "HIFIYF18.IMG"))
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)

    stock = open(a.stock, "rb").read()
    table, table_path = load_table(stock, a.allow_unverified)
    g = table["game"]
    GAME_CODE_RUN, GAME_DATA_RUN, SLOT = int(g["code_run"], 16), int(g["data_run"], 16), g["slot"]
    DATA_LIMIT = int(g["audio_data"], 16)             # the audio player's data starts here; stay below it
    CODE_LIMIT = GAME_CODE_RUN + CODE_ROOM
    POOL_B_END = int(g["audio_code"], 16) & ~0x7ff    # ... and its code here
    OLD_NAME = g["menu_name"]
    print("firmware %s, addresses from %s" % (table["name"], table_path))
    if CODE_LIMIT + 0x2000 > POOL_B_END:
        sys.exit("not enough RAM between the games' code and the audio player's in this firmware")
    with open(os.path.join(OUT, "fw_addrs.h"), "w") as f:
        f.write("/* generated by gameboy/build.py from %s - do not edit */\n" % table_path)
        for k, v in list(table["functions"].items()) + list(table["variables"].items()):
            f.write("#define FWA_%s %s\n" % (k, v))
        f.write("#define FWA_pool_b 0x%08x\n#define FWA_pool_b_end 0x%08x\n" % (CODE_LIMIT, POOL_B_END))

    cflags = ["--target=thumbv7m-none-eabi", "-mcpu=cortex-m3", "-mthumb", a.opt, "-ffreestanding", "-fno-builtin",
              "-nostdlib", "-ffunction-sections", "-fdata-sections", "-fno-unwind-tables",
              "-fno-asynchronous-unwind-tables", "-w", "-I" + os.path.join(HERE, "libc"), "-I" + OUT]
    objs = []
    for src in (os.path.join(HERE, "ap30_gb.c"),):
        o = os.path.join(OUT, os.path.basename(src)[:-2] + ".o")
        run(tool("clang"), *cflags, "-c", src, "-o", o)
        objs.append(o)
    elf = os.path.join(OUT, "gb.elf")
    run(tool("ld.lld"), "-T", os.path.join(ROOT, "common", "ap30.ld"), "--gc-sections", "-o", elf, *objs, "-Map=" + os.path.join(OUT, "gb.map"),
        "--defsym=GAME_CODE_RUN=0x%08x" % GAME_CODE_RUN, "--defsym=GAME_DATA_RUN=0x%08x" % GAME_DATA_RUN)
    und = subprocess.run([tool("llvm-nm"), "-u", elf], capture_output=True, text=True).stdout.strip()
    if und:
        sys.exit("undefined symbols:\n" + und)
    cbin, dbin = os.path.join(OUT, "code.bin"), os.path.join(OUT, "data.bin")
    run(tool("llvm-objcopy"), "-O", "binary", "-j", ".text", elf, cbin)
    run(tool("llvm-objcopy"), "-O", "binary", "-j", ".data", elf, dbin)
    code, data = open(cbin, "rb").read(), open(dbin, "rb").read()
    s = syms(elf)
    bss = s["__bss_end"] - s["__data_end"]
    assert s["__code_end"] - GAME_CODE_RUN == len(code) and s["__data_end"] - GAME_DATA_RUN == len(data)
    assert s["gw_window"] == GAME_DATA_RUN, "window structure is not first in .data"

    work = os.path.join(OUT, "work")
    shutil.rmtree(work, ignore_errors=True)
    run(sys.executable, os.path.join(ROOT, "tools", "rknanofw.py"), "unpack", a.stock, work)
    cb = bytearray(open(os.path.join(work, "code.bin"), "rb").read())
    BASE, n = struct.unpack_from("<II", cb, 0)
    ent = lambda i: struct.unpack_from("<8I", cb, 8 + 32 * i)
    cl, cr, cn, dl, dr, dn, ba, bn = ent(SLOT)
    assert cr == GAME_CODE_RUN and dr == GAME_DATA_RUN and dl == cl + cn

    code_room = CODE_LIMIT - GAME_CODE_RUN
    print("code %d/%d bytes (stock game %d alone had %d)" % (len(code), code_room, SLOT, cn))
    print("data %d + bss %d bytes: RAM 0x%08x-0x%08x (limit 0x%08x)" % (len(data), bss, GAME_DATA_RUN, s["__bss_end"], DATA_LIMIT))
    if len(code) > code_room:
        sys.exit("code reaches into cache pool B")
    if s["__bss_end"] > DATA_LIMIT:
        sys.exit("data and bss reach into memory the audio player uses")

    # file space: code from the start of the slot's module, data straight
    # after it; this runs past that module into the games stored after it
    pad = -len(code) % 4
    dl = cl + len(code) + pad
    f0, f1 = cl - BASE, dl - BASE + len(data)
    taken = []
    for i in range(n):
        e = ent(i)
        if i == SLOT or not e[2]:
            continue
        lo, hi = e[0] - BASE, e[3] - BASE + e[5]
        if lo < f1 and hi > f0:
            taken.append(i)
    if any(ent(i)[1] != GAME_CODE_RUN or ent(i)[4] != GAME_DATA_RUN for i in taken):
        sys.exit("the module would overwrite something that is not a game: modules %s" % taken)
    cb[f0:f1] = code + bytes(pad) + data
    new = (cl, cr, len(code), dl, dr, len(data), dr + len(data), bss)
    for i in [SLOT] + taken:
        struct.pack_into("<8I", cb, 8 + 32 * i, *new)
    open(os.path.join(work, "code.bin"), "wb").write(cb)
    print("games given up: modules %s (all now start the Game Boy)" % ([SLOT] + taken))

    # menu name, in every language block
    mp = os.path.join(work, "menu.bin")
    menu = bytearray(open(mp, "rb").read())
    langs = struct.unpack_from("<H", menu, 0)[0]
    offs = struct.unpack_from("<%dI" % langs, menu, 2)
    first = menu.find(OLD_NAME.encode("utf-16le"))
    if first < 0:
        sys.exit("menu entry %r not found" % OLD_NAME)
    rel = first - max(o for o in offs if o <= first)
    newname = a.name.encode("utf-16le")
    if len(newname) > 60:
        sys.exit("--name too long")
    for o in offs:
        p = o + rel
        end = p
        while menu[end:end + 2] != b"\0\0":
            end += 2
        assert end - p <= 64 and menu[p - 8:p] == b"\xff" * 8, "unexpected menu record at 0x%x" % p
        menu[p:max(end, p + len(newname))] = newname + bytes(max(end - p - len(newname), 0))
    open(mp, "wb").write(menu)
    print("menu: '%s' -> '%s' in %d languages" % (OLD_NAME, a.name, langs))

    y, m, d = a.date.split("-")
    hp = os.path.join(work, "header.bin")
    hdr = bytearray(open(hp, "rb").read())
    hdr[0:4] = bytes([int(y[2:], 16), int(y[:2], 16), int(d, 16), int(m, 16)])
    open(hp, "wb").write(hdr)
    img = os.path.join(OUT, os.path.basename(a.stock))
    run(sys.executable, os.path.join(ROOT, "tools", "rknanofw.py"), "pack", work, img)
    run(sys.executable, os.path.join(ROOT, "tools", "rknanofw.py"), "info", img)
    print("gb_frames at 0x%08x" % s["gb_frames"])


if __name__ == "__main__":
    main()
